// Популярні міста для швидкого вибору
export const POPULAR_CITIES = ["Київ", "Львів", "Одеса", "Харків", "Дніпро", "Вінниця"];

const norm = (s: string) =>
  s
    .toLowerCase()
    .replace(/[’ʼ`]/g, "'")
    .replace(/ё/g, "е")
    .trim();

export function findCity(name: string): City | undefined {
  const n = norm(name);
  return CITIES.find((c) => norm(c.name) === n);
}

// Пошук міста: спочатку ті, що починаються з запиту, потім — що містять його (також за назвою області)
export function searchCities(query: string, limit = 8): City[] {
  const q = norm(query);
  if (!q) return CITIES.filter((c) => POPULAR_CITIES.includes(c.name)).slice(0, limit);
  const starts = CITIES.filter((c) => norm(c.name).startsWith(q));
  const contains = CITIES.filter((c) => !starts.includes(c) && (norm(c.name).includes(q) || norm(c.region).includes(q)));
  return [...starts, ...contains].slice(0, limit);
}

// Приблизні межі України — для перевірки координат з карти
export const UA_BOUNDS = { minLat: 44.0, maxLat: 52.5, minLng: 22.0, maxLng: 40.5 };

export function isInUkraine(lat: number, lng: number): boolean {
  return lat >= UA_BOUNDS.minLat && lat <= UA_BOUNDS.maxLat && lng >= UA_BOUNDS.minLng && lng <= UA_BOUNDS.maxLng;
}

export function regionLabel(city: string, region: string): string {
  return city === region ? city : `${city}, ${region.replace(" область", " обл.")}`;
}
